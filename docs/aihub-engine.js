/* 발코니·실외기실과의 간격은 외벽 쪽 기준(더 넓다) */
const EXT_KINDS = ["balcony", "ac"];
const tolOf = (ca, cb, o) => (SPACE_CATS[ca] && EXT_KINDS.includes(SPACE_CATS[ca][0])) || (SPACE_CATS[cb] && EXT_KINDS.includes(SPACE_CATS[cb][0]))
  ? Math.max(o.wall_tol_px, o.wall_tol_ext_px) : o.wall_tol_px;
function contact(pa, pb, bba, bbb, o, tol = o.wall_tol_px) {
  if (bboxGap(bba, bbb) > tol) return [0, null];
  const sa = boundarySamples(pa, o.sample_step_px).filter(p => polyDist(p, pb) <= tol);
  const sb = boundarySamples(pb, o.sample_step_px).filter(p => polyDist(p, pa) <= tol);
  if (!sa.length || !sb.length) return [0, null];
  const all = sa.concat(sb);
  const mx = all.reduce((s, p) => s + p[0], 0) / all.length, my = all.reduce((s, p) => s + p[1], 0) / all.length;
  let best = all[0], bd = Infinity;
  for (const p of all) { const d = Math.hypot(p[0] - mx, p[1] - my); if (d < bd) { bd = d; best = p; } }
  return [Math.min(sa.length, sb.length) * o.sample_step_px, best];
}

